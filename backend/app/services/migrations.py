import argparse
from datetime import datetime, timezone

from sqlalchemy import inspect, text

from app.services import database

CURRENT_SCHEMA_VERSION = 2


def _table_columns(connection, table_name: str) -> set[str]:
    return {column["name"] for column in inspect(connection).get_columns(table_name)}


def _create_legacy_schema(connection) -> None:
    is_sqlite = connection.dialect.name == "sqlite"
    identity = (
        "INTEGER PRIMARY KEY AUTOINCREMENT"
        if is_sqlite
        else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    rate_limit_timestamp_type = "REAL" if is_sqlite else "DOUBLE PRECISION"

    connection.execute(text(f"""
        CREATE TABLE IF NOT EXISTS agent_runs (
            id {identity},
            created_at TEXT NOT NULL,
            provider TEXT NOT NULL,
            agent_name TEXT NOT NULL,
            message_length INTEGER NOT NULL,
            success INTEGER NOT NULL,
            error_type TEXT,
            model TEXT,
            completed_at TEXT,
            duration_ms INTEGER,
            result_summary TEXT,
            tools_json TEXT
        )
    """))
    old_columns = _table_columns(connection, "agent_runs")
    additions = {
        "model": "TEXT",
        "completed_at": "TEXT",
        "duration_ms": "INTEGER",
        "result_summary": "TEXT",
        "tools_json": "TEXT",
    }
    for column, column_type in additions.items():
        if column not in old_columns:
            connection.execute(
                text(f"ALTER TABLE agent_runs ADD COLUMN {column} {column_type}")
            )
    if "completed_at" not in old_columns:
        connection.execute(text(
            "UPDATE agent_runs SET completed_at = created_at "
            "WHERE completed_at IS NULL"
        ))

    connection.execute(text(f"""
        CREATE TABLE IF NOT EXISTS tool_runs (
            id {identity},
            created_at TEXT NOT NULL,
            conversation_id TEXT,
            tool_name TEXT NOT NULL,
            status TEXT NOT NULL,
            detail TEXT
        )
    """))
    connection.execute(text("""
        CREATE TABLE IF NOT EXISTS saved_agents (
            agent_id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            description TEXT NOT NULL,
            config_json TEXT NOT NULL,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        )
    """))
    connection.execute(text(f"""
        CREATE TABLE IF NOT EXISTS gemini_rate_limit_events (
            client_ip TEXT NOT NULL,
            created_at {rate_limit_timestamp_type} NOT NULL
        )
    """))
    connection.execute(text("""
        CREATE INDEX IF NOT EXISTS idx_gemini_rate_limit_client_created
        ON gemini_rate_limit_events (client_ip, created_at)
    """))
    connection.execute(text("""
        CREATE INDEX IF NOT EXISTS idx_gemini_rate_limit_created
        ON gemini_rate_limit_events (created_at)
    """))


def _add_owner_column(connection, table_name: str) -> None:
    if "owner_id" not in _table_columns(connection, table_name):
        connection.execute(text(
            f"ALTER TABLE {table_name} ADD COLUMN owner_id TEXT "
            "REFERENCES users(id)"
        ))
    connection.execute(text(
        f"CREATE INDEX IF NOT EXISTS idx_{table_name}_owner_id ON {table_name}(owner_id)"
    ))


def _create_auth_schema(connection) -> None:
    connection.execute(text("""
        CREATE TABLE IF NOT EXISTS users (
            id TEXT PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            display_name TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL CHECK (role IN ('user', 'admin')),
            status TEXT NOT NULL CHECK (status IN ('active', 'disabled')),
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            last_login_at TEXT
        )
    """))
    connection.execute(text("""
        CREATE TABLE IF NOT EXISTS sessions (
            id TEXT PRIMARY KEY,
            user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            token_hash TEXT NOT NULL UNIQUE,
            created_at TEXT NOT NULL,
            expires_at TEXT NOT NULL,
            revoked_at TEXT,
            last_used_at TEXT
        )
    """))
    connection.execute(text("""
        CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions(user_id)
    """))
    connection.execute(text("""
        CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at)
    """))

    identity = (
        "INTEGER PRIMARY KEY AUTOINCREMENT"
        if connection.dialect.name == "sqlite"
        else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    connection.execute(text(f"""
        CREATE TABLE IF NOT EXISTS audit_logs (
            id {identity},
            actor_user_id TEXT REFERENCES users(id),
            action TEXT NOT NULL,
            target_type TEXT,
            target_id TEXT,
            outcome TEXT NOT NULL,
            created_at TEXT NOT NULL,
            metadata_json TEXT NOT NULL DEFAULT '{{}}'
        )
    """))
    connection.execute(text("""
        CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
        ON audit_logs(created_at)
    """))
    connection.execute(text("""
        CREATE TABLE IF NOT EXISTS bootstrap_state (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL
        )
    """))

    for table_name in ("agent_runs", "tool_runs", "saved_agents"):
        _add_owner_column(connection, table_name)


def upgrade_schema(database_url: str) -> int:
    with database.transaction(database_url) as connection:
        if connection.dialect.name == "postgresql":
            connection.execute(text("SELECT pg_advisory_xact_lock(714223891)"))
        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS schema_migrations (
                version INTEGER PRIMARY KEY,
                applied_at TEXT NOT NULL
            )
        """))
        applied = {
            row["version"]
            for row in connection.execute(
                text("SELECT version FROM schema_migrations")
            ).mappings()
        }
        migrations = {
            1: _create_legacy_schema,
            2: _create_auth_schema,
        }
        for version, migration in migrations.items():
            if version in applied:
                continue
            migration(connection)
            connection.execute(
                text("INSERT INTO schema_migrations (version, applied_at) "
                     "VALUES (:version, :applied_at)"),
                {
                    "version": version,
                    "applied_at": datetime.now(timezone.utc).isoformat(),
                },
            )
        return CURRENT_SCHEMA_VERSION


def get_schema_version(database_url: str) -> int:
    with database.transaction(database_url) as connection:
        if "schema_migrations" not in inspect(connection).get_table_names():
            return 0
        row = connection.execute(
            text("SELECT MAX(version) AS version FROM schema_migrations")
        ).mappings().fetchone()
        return int(row["version"] or 0)


def require_current_schema(database_url: str) -> None:
    version = get_schema_version(database_url)
    if version != CURRENT_SCHEMA_VERSION:
        raise RuntimeError(
            "Database schema is not current. Run the documented migration command "
            "before starting the production application."
        )


def main() -> None:
    from app.services import db

    parser = argparse.ArgumentParser(description="Manage AGENT_FORGE database schema.")
    parser.add_argument("command", choices=("upgrade", "version"))
    arguments = parser.parse_args()
    if arguments.command == "upgrade":
        version = upgrade_schema(db.get_database_url())
        print(f"Database schema is at version {version}.")
    else:
        print(f"Database schema version: {get_schema_version(db.get_database_url())}.")


if __name__ == "__main__":
    main()
